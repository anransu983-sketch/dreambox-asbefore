object PetTalk {

    enum class Pool { IDLE, MORNING, NOON, EVENING, NIGHT, POKE, TICKLE, GRAB, FED, SLEEPY, DIZZY, PEEK, HANG }

    private val recent = ArrayDeque<String>()

    fun line(pool: Pool): String {
        val all = lines(pool)
        var pick = all.random()
        if (all.size > 4) {
            var guard = 0
            while (recent.contains(pick) && guard < 6) {
                pick = all.random()
                guard++
            }
        }
        recent.addLast(pick)
        while (recent.size > 10) recent.removeFirst()
        return pick
    }

    fun timePool(): Pool {
        return when (Calendar.getInstance().get(Calendar.HOUR_OF_DAY)) {
            in 5..10 -> Pool.MORNING
            in 11..13 -> Pool.NOON
            in 17..22 -> Pool.EVENING
            in 14..16 -> Pool.IDLE
            else -> Pool.NIGHT
        }
    }

    /** 日常碎碎念：六成日常池，四成当前时段池。 */
    fun idlePool(): Pool = if (Random.nextInt(100) < 62) Pool.IDLE else timePool()

